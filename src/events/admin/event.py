class EventOriginFilter(admin.SimpleListFilter):
    """Filter events by how they came to exist: hand-made, generated by a recurrence, or a series template."""

    title = "origin"
    parameter_name = "origin"

    def lookups(self, request: HttpRequest, model_admin: admin.ModelAdmin) -> list[tuple[str, str]]:  # type: ignore[type-arg]
        return [("manual", "Manual"), ("occurrence", "Recurring occurrence"), ("template", "Template")]

    def queryset(self, request: HttpRequest, queryset: QuerySet[models.Event]) -> QuerySet[models.Event]:
        if self.value() == "manual":
            return t.cast(EventQuerySet, queryset).manually_created()
        if self.value() == "occurrence":
            return queryset.filter(is_template=False, occurrence_index__isnull=False)
        if self.value() == "template":
            return queryset.filter(is_template=True)
        return queryset


@admin.register(models.Event)
class EventAdmin(ImageSourceAdminMixin, ModelAdmin, OrganizationLinkMixin):  # type: ignore[misc]
    """Admin model for Events."""

    def get_readonly_fields(self, request: HttpRequest, obj: models.Event | None = None) -> t.Sequence[str]:
        """Make ``requires_ticket`` create-only (#1295) and ``status`` action-only (#1535).

        Flipping ``requires_ticket`` later strands tiers and tickets. A status change must go through
        ``update_status`` (see the actions below) to keep its guards and side effects.
        """
        fields = list(super().get_readonly_fields(request, obj))
        return [*fields, "requires_ticket", "status"] if obj is not None else fields

    def delete_model(self, request: HttpRequest, obj: models.Event) -> None:
        event_update_service.delete_event(obj)

    def delete_queryset(self, request: HttpRequest, queryset: QuerySet[models.Event]) -> None:
        # Each delete_event locks only its own rows, so lock the rows of the whole selection in the global order
        # first, or the loop can deadlock with a checkout cancel or a series pass that spans the events.
        pending_checkout.lock_for_bulk_delete(
            models.Ticket.objects.filter(event__in=queryset),
            tiers=models.TicketTier.objects.filter(event__in=queryset),
            parents=[models.Event.objects.filter(pk__in=queryset)],
        )
        for event in queryset:
            self.delete_model(request, event)

    def _set_status(
        self, request: HttpRequest, queryset: QuerySet[models.Event], status: models.Event.EventStatus
    ) -> None:
        changed = failed = 0
        user = t.cast(RevelUser, request.user)
        for pk in queryset.values_list("pk", flat=True):
            try:
                with transaction.atomic():
                    # Decide on the locked row, not the changelist snapshot: the event can change meanwhile.
                    event = models.Event.objects.select_for_update().filter(pk=pk).first()
                    if event is None or event.status == status:  # a same-status cancel would wipe the reason
                        continue
                    reason = event.cancellation_reason if status == models.Event.EventStatus.CANCELLED else None
                    event_update_service.update_status(event, status, cancellation_reason=reason, initiated_by=user)
            except EventRefundsStartedError as exc:
                failed += 1
                self.message_user(request, f"{event}: {exc}", messages.ERROR)
            except ValidationError as exc:
                failed += 1
                self.message_user(request, f"{event}: {format_validation_error(exc)}", messages.ERROR)
            else:
                changed += 1
        if changed:
            self.message_user(request, f"Set {changed} event(s) to {status.label}.", messages.SUCCESS)
        elif not failed:
            self.message_user(
                request, f"No event changed: the selected events are already {status.label}.", messages.INFO
            )

    @admin.action(description="Open selected events", permissions=["change"])
    def open_events(self, request: HttpRequest, queryset: QuerySet[models.Event]) -> None:
        self._set_status(request, queryset, models.Event.EventStatus.OPEN)

    @admin.action(description="Close selected events", permissions=["change"])
    def close_events(self, request: HttpRequest, queryset: QuerySet[models.Event]) -> None:
        self._set_status(request, queryset, models.Event.EventStatus.CLOSED)

    @admin.action(description="Set selected events to draft", permissions=["change"])
    def draft_events(self, request: HttpRequest, queryset: QuerySet[models.Event]) -> None:
        self._set_status(request, queryset, models.Event.EventStatus.DRAFT)

    @admin.action(description="Cancel selected events (no refunds)", permissions=["change"])
    def cancel_events(self, request: HttpRequest, queryset: QuerySet[models.Event]) -> None:
        self._set_status(request, queryset, models.Event.EventStatus.CANCELLED)

    actions = ["open_events", "close_events", "draft_events", "cancel_events"]

    def save_model(self, request: HttpRequest, obj: models.Event, form: t.Any, change: bool) -> None:
        """Keep day-membership records on the event window when staff move an upcoming event's dates."""
        super().save_model(request, obj, form, change)
        old_end = form.initial.get("end")
        if change and {"start", "end"} & set(form.changed_data) and old_end and old_end > timezone.now():
            day_membership_service.resync_event_window(obj)

    list_display = [
        "name",
        "organization_link",
        "city_display",
        "open_on_revel",
        "event_type",
        "visibility",
        "status",
        "start",
        "created_at",
        "attendee_count",
        "requires_ticket",
        "origin",
    ]
    list_select_related = ["organization", "city", "venue__city"]
    list_filter = [
        "status",
        "visibility",
        "event_type",
        ("organization", AutocompleteSelectFilter),
        "start",
        "requires_ticket",
        "waitlist_open",
        ("created_at", InclusiveRangeDateFilter),
        EventOriginFilter,
    ]
    list_filter_submit = True
    search_fields = ["name", "slug", "organization__name"]
    readonly_fields = ["id", "view_on_revel"]
    autocomplete_fields = ["organization", "event_series", "city", "venue"]
    prepopulated_fields = {"slug": ("name",)}
    date_hierarchy = "start"
    ordering = ["-created_at"]

    tabs = [
        ("Details", ["Details"]),
        ("Attendees", ["RSVPs", "Tickets", "Invitations", "Waitlist"]),
        ("Configuration", ["Tiers & Resources"]),
    ]

    fieldsets = [
        (
            "Details",
            {
                "fields": (
                    "id",
                    "view_on_revel",
                    "organization",
                    ("name", "slug"),
                    "venue",
                    ("city", "address"),
                    "description",
                    "invitation_message",
                    ("logo", "cover_art"),
                )
            },
        ),
        (
            "Configuration",
            {
                "fields": (
                    ("event_type", "visibility", "status"),
                    "cancellation_reason",
                    ("start", "end", "is_open_ended"),
                    "event_series",
                    ("max_attendees", "max_tickets_per_user"),
                    (
                        "potluck_open",
                        "accept_invitation_requests",
                        "accept_rsvp_notes",
                        "can_attend_without_login",
                        "require_ticket_names",
                        "requires_full_profile",
                    ),
                    "requires_ticket",
                    "visibility_settings",
                    ("rsvp_before", "apply_before"),
                    ("check_in_starts_at", "check_in_ends_at"),
                )
            },
        ),
        (
            "Waitlist",
            {
                "fields": (
                    "waitlist_open",
                    "waitlist_time_window",
                    "waitlist_batch_size",
                    "waitlist_lottery_mode",
                    "waitlist_cutoff_date",
                ),
            },
        ),
    ]

    inlines = [
        EventRSVPInline,
        TicketInline,
        EventInvitationInline,
        EventWaitListInline,
        TicketTierInline,
        WaitlistOfferInline,
    ]

    @admin.display(description="City")
    def city_display(self, obj: models.Event) -> str:
        city = obj.city or (obj.venue.city if obj.venue else None)
        return format_city(city)

    @admin.display(description="Open")
    def open_on_revel(self, obj: models.Event) -> str:
        return view_on_revel_link(frontend_url(f"/events/{obj.pk}"))

    @admin.display(description="View on Revel")
    def view_on_revel(self, obj: models.Event | None) -> str:
        if obj is None or obj._state.adding:
            return "—"
        return view_on_revel_link(frontend_url(f"/events/{obj.pk}"))

    @admin.display(description="Origin")
    def origin(self, obj: models.Event) -> str:
        if obj.is_template:
            return "Template"
        return "Manual" if obj.occurrence_index is None else "Recurring occurrence"


@admin.register(models.EventSeries)
class EventSeriesAdmin(ImageSourceAdminMixin, ModelAdmin, OrganizationLinkMixin):  # type: ignore[misc]
    list_display = ["name", "slug", "organization_link", "is_active", "auto_publish"]
    list_select_related = ["organization"]
